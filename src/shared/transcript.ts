/**
 * The only module that knows the transcript format under ~/.claude/projects/.
 * That format is undocumented and can change between releases, so everything
 * here fails soft: any surprise returns null and the goal shows as unknown.
 */
import * as fs from 'node:fs';

const READ_LIMIT = 512 * 1024;

function textOf(content: unknown): string | null {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return null;
  const parts = content
    .filter((part) => part && typeof part === 'object' && part.type === 'text' && typeof part.text === 'string')
    .map((part) => part.text as string);
  return parts.length ? parts.join('\n') : null;
}

function cleanPrompt(raw: string): string | null {
  // Slash commands are stored as tags; show them the way they were typed.
  const command = raw.match(/<command-name>([^<]+)<\/command-name>/);
  if (command) {
    const args = raw.match(/<command-args>([^<]*)<\/command-args>/);
    return `${command[1].trim()} ${args ? args[1].trim() : ''}`.trim();
  }
  const text = raw.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '').trim();
  if (!text) return null;
  // Local command output and other harness-written entries, not something the user asked for.
  if (/^<(local-command|bash-|task-notification|user-prompt-submit-hook)/.test(text)) return null;
  if (text.startsWith('Caveat: The messages below were generated by the user while running local commands')) return null;
  return text;
}

/** First thing the user asked for in this session, or null. */
export function firstUserPrompt(transcriptPath: string | null): string | null {
  if (!transcriptPath || !transcriptPath.endsWith('.jsonl')) return null;
  let fd: number | null = null;
  try {
    fd = fs.openSync(transcriptPath, 'r');
    const buffer = Buffer.alloc(READ_LIMIT);
    const read = fs.readSync(fd, buffer, 0, READ_LIMIT, 0);
    const lines = buffer.subarray(0, read).toString('utf8').split('\n');
    // A full buffer probably cut the last line in half.
    if (read === READ_LIMIT) lines.pop();

    for (const line of lines) {
      if (!line.trim()) continue;
      let entry: any;
      try {
        entry = JSON.parse(line);
      } catch {
        continue;
      }
      if (!entry || entry.type !== 'user' || entry.isMeta || entry.isSidechain) continue;
      const text = textOf(entry.message?.content);
      if (!text) continue;
      const prompt = cleanPrompt(text);
      if (prompt) return prompt;
    }
    return null;
  } catch {
    return null;
  } finally {
    if (fd !== null) {
      try {
        fs.closeSync(fd);
      } catch {
        // ignore
      }
    }
  }
}
